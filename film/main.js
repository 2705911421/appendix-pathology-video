import {initBaker,bake} from './lib/wash.js';
import {bakeHE} from './lib/he.js';
import s08 from './chapters/s08.js';
import {forScene} from './timeline.js';
const name=new URLSearchParams(location.search).get('scene')||'s08';
if(!['s08','s10','gross_test'].includes(name))throw Error('Unknown scene '+name);
const scene=name==='s08'?s08:name==='s10'?(await import('./chapters/s10.js')).default:(await import('./chapters/gross_test.js')).default;
const clock=name==='s08'?{duration:T.end(34),T}:name==='s10'?forScene(37,42):{duration:5,T:null};
import {T} from './timeline.js';
const c=document.getElementById('c');c.width=1920;c.height=1080;const ctx=c.getContext('2d');
await document.fonts.load('500 32px MixSans');await document.fonts.load('700 40px MixSans');await document.fonts.load('800 52px MixSans');
await initBaker();
if(name!=='gross_test')bakeHE((k,r,o)=>bake(k,r,{...o,hd:true,soft:true,grain:.12,edge:.3,bleed:.5}));
scene.prepare();window.DUR=clock.duration;window.render=t=>scene.draw(ctx,t,clock.T);window.READY=true;
