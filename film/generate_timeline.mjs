import fs from 'node:fs';
// Regenerate after a full narration replacement; never read credential files.
const source=process.argv[2]||'/workspace/病理科普视频/配音/全稿_v3/timeline.json';
const raw=JSON.parse(fs.readFileSync(source,'utf8'));
if(!Array.isArray(raw.lines)||!raw.lines.length)throw Error('Missing sentence lines');
const ids=new Set();
for(const s of raw.lines){
 if(ids.has(s.n)||!Number.isInteger(s.n)||!Number.isFinite(s.start)||!Number.isFinite(s.end)||s.end<=s.start)throw Error('Invalid sentence '+s.n);
 ids.add(s.n);
}
fs.writeFileSync(new URL('./timing_snapshot.js',import.meta.url),'// Generated by generate_timeline.mjs; regenerate after narration replacement.\nexport const timing = '+JSON.stringify(raw.lines,null,2)+';\n');
